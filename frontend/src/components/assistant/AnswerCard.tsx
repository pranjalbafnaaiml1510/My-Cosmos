import { Fragment, useState } from "react";
import { Link } from "react-router-dom";
import type { AskResponse } from "../../types";
import { Chip, GlassCard } from "../ui/primitives";

const PROVIDER_NOTE = (p: string) =>
  p === "extractive"
    ? "Extractive answer: sentences quoted verbatim from the cited abstracts. No language model was used."
    : `Generated by ${p.replace("anthropic:", "Claude ")} from the numbered sources only, then checked: citations to sources that don't exist are removed.`;

/** Renders an answer with clickable [n] citations linked to the source list below it. */
export function AnswerCard({ r, id, compact = false }: { r: AskResponse; id: string; compact?: boolean }) {
  const [active, setActive] = useState<number | null>(null);
  const focus = (n: number) => {
    setActive(n);
    document.getElementById(`${id}-src-${n}`)?.scrollIntoView({ behavior: "smooth", block: "nearest" });
  };
  const parts = r.answer.split(/(\[\d+\])/g);
  const sources = r.status === "answered" ? r.sources : r.sources.slice(0, 3);
  const g = r.grounding;

  return (
    <GlassCard as="article" className={`animate-rise ${compact ? "p-4" : "p-6"}`}>
      {!compact && r.interpretation.length > 0 && (
        <p className="mb-3 flex flex-wrap items-center gap-1.5 text-xs text-navy-500">Interpreted as: {r.interpretation.map((t) => <Chip key={t}>{t}</Chip>)}</p>
      )}

      {r.status === "answered" ? (
        <p className={`leading-relaxed text-navy-900 ${compact ? "text-sm" : "text-[1.05rem]"}`}>
          {parts.map((part, i) => {
            const m = part.match(/^\[(\d+)\]$/);
            if (!m) return <Fragment key={i}>{part}</Fragment>;
            const n = Number(m[1]);
            return (
              <button key={i} type="button" onClick={() => focus(n)} aria-label={`Source ${n}: ${r.sources[n - 1]?.paper.title ?? ""}`}
                className={`mx-0.5 rounded px-1 align-super text-[0.7em] font-semibold transition ${active === n ? "bg-violet-500 text-white" : "bg-lavender-100 text-violet-600 hover:bg-lavender-200"}`}>
                {n}
              </button>
            );
          })}
        </p>
      ) : (
        <div role="status" className={`rounded-xl px-4 py-3 ${r.status === "error" ? "bg-blush-100" : "bg-dusty-100"}`}>
          <p className="font-medium text-navy-900">{r.answer}</p>
          {r.status === "insufficient_evidence" && (
            <p className="mt-1 text-sm text-navy-500">
              {r.sources.length ? "The closest papers below don't address the question well enough to answer it." : "No sufficiently relevant papers were retrieved."} Try rephrasing, or narrow it to a topic.
            </p>
          )}
        </div>
      )}

      <div className="mt-4 flex flex-wrap items-center gap-x-4 gap-y-1 text-xs text-navy-500">
        {r.status === "answered" && (
          <span title="Sentences that carry at least one citation">
            <span className="font-semibold tabular-nums text-navy-700">{g.cited_sentences}/{g.sentences}</span> sentences cited
          </span>
        )}
        {g.invalid_citations.length > 0 && <span className="text-navy-700">{g.invalid_citations.length} invalid citation(s) removed</span>}
        <span>{PROVIDER_NOTE(r.provider)}</span>
      </div>

      {sources.length > 0 && (
        <div className="mt-5 border-t border-lavender-100 pt-4">
          <h3 className="text-xs font-semibold uppercase tracking-wider text-navy-500">
            {r.status === "answered" ? "Sources" : "Closest papers retrieved"}
          </h3>
          <ol className="mt-2 space-y-2">
            {sources.map((s) => {
              const used = r.cited.includes(s.n);
              return (
                <li key={s.n} id={`${id}-src-${s.n}`}
                  className={`flex gap-3 rounded-xl p-2 text-sm transition ${active === s.n ? "bg-lavender-100" : used ? "bg-white/50" : ""}`}>
                  <span className={`grid h-6 w-6 shrink-0 place-items-center rounded-full text-xs font-semibold ${used ? "bg-violet-500 text-white" : "bg-lavender-100 text-violet-600"}`}>{s.n}</span>
                  <div className="min-w-0">
                    <Link to={`/papers/${s.paper.paper_id}`} className="font-medium leading-snug text-navy-900 hover:text-violet-600">{s.paper.title}</Link>
                    <p className="text-xs text-navy-500">
                      {s.paper.publication_year}{s.paper.country ? ` · ${s.paper.country}` : ""} · relevance {s.relevance}%{!used && r.status === "answered" ? " · retrieved, not cited" : ""}
                    </p>
                    {!compact && active === s.n && <p className="mt-1 text-xs leading-relaxed text-navy-700">{s.passage}</p>}
                  </div>
                </li>
              );
            })}
          </ol>
        </div>
      )}
    </GlassCard>
  );
}
